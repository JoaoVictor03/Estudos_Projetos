#Listas -> Dados ordenados e mutáveis []
frutas = ["Maçã", "Banana", "Manga"]
print(frutas)
print(frutas[1])
frutas[1] = "Abacate"
print(frutas)
frutas.sort() #Ordanando as frutas
print(frutas)
#Métodos de listas permitem manipular os dados dentro da listas
numeros  = [1, 2, 3, 4]

numeros_quadrados = [numero ** 2 for numero in numeros]
print(numeros_quadrados)

